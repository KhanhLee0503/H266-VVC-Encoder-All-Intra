//-----------------------------------------------------------
// Description: Self-checking SystemVerilog testbench for the
// unified raw inverse DCT-II core (4/8/16/32-point).
// Drives all external stimulus at posedge I_CLK, including
// deliberate output stalls and gaps between input beats.
// Checks 4-lane arithmetic against an independently encoded
// integer transform matrix, output order, DATA_LAST and
// stable ready/valid payload under backpressure.
// Prints the entire input and raw output vector for each TC.
// No external .mem files are required.
//-----------------------------------------------------------
`timescale 1ns/1ps
module TQ_IDCT2_CORE_TB;
  localparam PARA_DATA_WD = 16;
  localparam PARA_RESULT_WD = 28;
  localparam PARA_TC_COUNT = 20;

  logic I_CLK;
  logic I_RESETN;
  logic [1:0] I_TRANSFORM_SIZE;
  logic [4*PARA_DATA_WD-1:0] I_DATA;
  logic I_DATA_VALID;
  logic I_DATA_READY;
  logic [4*PARA_RESULT_WD-1:0] O_DATA;
  logic O_DATA_VALID;
  logic O_DATA_READY;
  logic O_DATA_LAST;

  integer r_matrix32 [0:31][0:31];
  integer r_coeff [0:PARA_TC_COUNT-1][0:31];
  integer r_golden [0:PARA_TC_COUNT-1][0:31];
  integer r_rtl [0:31];
  integer r_cycle;
  integer r_completed;
  integer r_output_beat;
  integer r_stall_cycles;
  integer r_last_stall_cycles;
  integer r_expected_size;
  integer r_received_sample_idx;
  integer signed w_received;
  logic r_was_stalled;
  logic [4*PARA_RESULT_WD-1:0] r_stalled_data;
  logic r_stalled_last;

  TQ_IDCT2_CORE #(
    .PARA_DATA_WD(PARA_DATA_WD),
    .PARA_RESULT_WD(PARA_RESULT_WD)
  ) u_dut (
    .I_CLK(I_CLK),
    .I_RESETN(I_RESETN),
    .I_TRANSFORM_SIZE(I_TRANSFORM_SIZE),
    .I_DATA(I_DATA),
    .I_DATA_VALID(I_DATA_VALID),
    .I_DATA_READY(I_DATA_READY),
    .O_DATA(O_DATA),
    .O_DATA_VALID(O_DATA_VALID),
    .O_DATA_READY(O_DATA_READY),
    .O_DATA_LAST(O_DATA_LAST)
  );

  initial begin
    I_CLK = 1'b0;
    forever #5 I_CLK = ~I_CLK;
  end

  // Output backpressure is driven on posedge only.
  always @(posedge I_CLK) begin
    if (!I_RESETN) begin
      r_cycle <= 0;
      O_DATA_READY <= 1'b0;
    end
    else begin
      r_cycle <= r_cycle + 1;
      O_DATA_READY <= ((r_cycle % 19) >= 11);
    end
  end

  always @(posedge I_CLK) begin
    if (!I_RESETN) begin
      r_completed = 0;
      r_output_beat = 0;
      r_stall_cycles = 0;
      r_last_stall_cycles = 0;
      r_was_stalled = 1'b0;
      r_stalled_data = '0;
      r_stalled_last = 1'b0;
    end
    else begin
      if (r_was_stalled && (!O_DATA_VALID || O_DATA !== r_stalled_data || O_DATA_LAST !== r_stalled_last))
        $fatal(1, "[FAIL] Output changed under stall at TC=%0d beat=%0d", r_completed+1, r_output_beat);

      if (O_DATA_VALID && !O_DATA_READY) begin
        r_stall_cycles = r_stall_cycles + 1;
        if (O_DATA_LAST)
          r_last_stall_cycles = r_last_stall_cycles + 1;
      end

      if (O_DATA_VALID && O_DATA_READY) begin
        if (r_completed >= PARA_TC_COUNT)
          $fatal(1, "[FAIL] Extra output vector");
        r_expected_size = 4 << (r_completed / 5);
        if (O_DATA_LAST !== (r_output_beat == (r_expected_size / 4)-1))
          $fatal(1, "[FAIL] O_DATA_LAST at TC=%0d beat=%0d", r_completed+1, r_output_beat);

        for (integer lane_idx = 0; lane_idx < 4; lane_idx++) begin
          r_received_sample_idx = 4*r_output_beat + lane_idx;
          w_received = $signed(O_DATA[lane_idx*PARA_RESULT_WD +: PARA_RESULT_WD]);
          r_rtl[r_received_sample_idx] = w_received;
          if (w_received !== r_golden[r_completed][r_received_sample_idx])
            $fatal(1, "[FAIL] TC%0d size=%0d X[%0d] RTL=%0d GOLDEN=%0d",
              r_completed+1, r_expected_size, r_received_sample_idx,
              w_received, r_golden[r_completed][r_received_sample_idx]);
        end
        if (O_DATA_LAST) begin
          $display("====================================================");
          $display("[PASS TC%0d] IDCT2 %0d-point raw", r_completed+1, r_expected_size);
          $display("  Input coefficients C[k]:");
          for (integer i = 0; i < r_expected_size; i += 4)
            $display("  C[%0d..%0d] = %0d %0d %0d %0d", i, i+3,
              r_coeff[r_completed][i], r_coeff[r_completed][i+1],
              r_coeff[r_completed][i+2], r_coeff[r_completed][i+3]);
          $display("  Reconstructed raw output RTL (each equals golden):");
          for (integer i = 0; i < r_expected_size; i += 4)
            $display("  X[%0d..%0d] = %0d %0d %0d %0d", i, i+3,
              r_rtl[i], r_rtl[i+1], r_rtl[i+2], r_rtl[i+3]);
          r_completed = r_completed + 1;
          r_output_beat = 0;
        end
        else
          r_output_beat = r_output_beat + 1;
      end
      r_was_stalled = O_DATA_VALID && !O_DATA_READY;
      r_stalled_data = O_DATA;
      r_stalled_last = O_DATA_LAST;
    end
  end

  // One input beat is accepted only upon VALID && READY at
  // posedge. Producer changes all signals using nonblocking
  // assignments at posedge; it never drives at negedge.
  task automatic send_vector(input integer tc_idx);
    integer num_samples;
    integer num_beats;
    logic [1:0] size_code;
    begin
      size_code = 2'(tc_idx / 5);
      num_samples = 4 << size_code;
      num_beats = num_samples / 4;
      for (integer beat_idx = 0; beat_idx < num_beats; beat_idx++) begin
        @(posedge I_CLK);
        I_TRANSFORM_SIZE <= size_code;
        I_DATA_VALID <= 1'b1;
        for (integer lane_idx = 0; lane_idx < 4; lane_idx++)
          I_DATA[lane_idx*PARA_DATA_WD +: PARA_DATA_WD] <= 16'(r_coeff[tc_idx][4*beat_idx+lane_idx]);
        do @(posedge I_CLK); while (!I_DATA_READY);
        I_DATA_VALID <= 1'b0;
        if ((beat_idx % 2) == 0)
          @(posedge I_CLK);
      end
    end
  endtask

