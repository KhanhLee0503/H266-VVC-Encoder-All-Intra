//-----------------------------------------------------------
// Description: Self-checking testbench for a unified inverse
// DST7/DCT8 transform core, N = 4, 8, 16, 32.
// Thirty-two test vectors cover zero, impulses, mixed signed,
// signed extrema including -32768 on an odd DCT8 coefficient,
// all transform sizes/modes, zero-out and output stalls.
// The scoreboard computes output directly from VTM integer
// FORWARD matrix data transposed (not from DUT routing).
// ALL external stimulus is driven at posedge using NBA updates.
//-----------------------------------------------------------
`timescale 1ns/1ps
module TQ_IDST7_IDCT8_CORE_TB;
  localparam integer PARA_DATA_WD = 16;
  localparam integer PARA_RESULT_WD = 28;
  localparam integer PARA_TC_COUNT = 32;

  logic I_CLK;
  logic I_RESETN;
  logic [1:0] I_TRANSFORM_SIZE;
  logic I_TRANSFORM_MODE;
  logic I_DATA_VALID;
  logic O_DATA_READY;
  logic [4*PARA_DATA_WD-1:0] I_DATA;
  logic O_DATA_VALID;
  logic I_DATA_READY;
  logic [4*PARA_RESULT_WD-1:0] O_DATA;
  logic O_DATA_LAST;

  integer r_ref_matrix [0:3][0:31][0:31];
  integer r_coefficients [0:PARA_TC_COUNT-1][0:31];
  integer r_golden [0:PARA_TC_COUNT-1][0:31];
  integer r_rtl_result [0:31];
  integer r_completed;
  integer r_output_beat;
  integer r_cycle;
  integer r_stalled;
  integer r_last_stalled;
  integer r_expected_size;
  integer r_sample_idx;
  integer r_child_beat;
  logic r_previous_stall;
  logic [4*PARA_RESULT_WD-1:0] r_previous_data;
  logic r_previous_last;
  integer signed w_sample;

  TQ_IDST7_IDCT8_CORE #(
    .PARA_DATA_WD(PARA_DATA_WD),
    .PARA_RESULT_WD(PARA_RESULT_WD)
  ) u_dut (
    .I_CLK(I_CLK),
    .I_RESETN(I_RESETN),
    .I_TRANSFORM_SIZE(I_TRANSFORM_SIZE),
    .I_TRANSFORM_MODE(I_TRANSFORM_MODE),
    .I_DATA_VALID(I_DATA_VALID),
    .O_DATA_READY(O_DATA_READY),
    .I_DATA(I_DATA),
    .O_DATA_VALID(O_DATA_VALID),
    .I_DATA_READY(I_DATA_READY),
    .O_DATA(O_DATA),
    .O_DATA_LAST(O_DATA_LAST)
  );

  initial begin
    I_CLK = 1'b0;
    forever #5 I_CLK = ~I_CLK;
  end

  // Deterministic backpressure, driven only on rising edges.
  always @(posedge I_CLK) begin
    if (!I_RESETN) begin
      r_cycle <= 0;
      I_DATA_READY <= 1'b0;
    end
    else begin
      r_cycle <= r_cycle + 1;
      I_DATA_READY <= ((r_cycle % 17) >= 9);
    end
  end

  // Output scoreboard samples the handshake before NBA changes.
  always @(posedge I_CLK) begin
    if (!I_RESETN) begin
      r_completed = 0;
      r_output_beat = 0;
      r_child_beat = 0;
      r_stalled = 0;
      r_last_stalled = 0;
      r_previous_stall = 1'b0;
      r_previous_data = '0;
      r_previous_last = 1'b0;
    end
    else begin
      if (r_previous_stall &&
          (!O_DATA_VALID || O_DATA !== r_previous_data || O_DATA_LAST !== r_previous_last))
        $fatal(1, "[FAIL] Output changes while stalled TC=%0d beat=%0d", r_completed, r_output_beat);

      if (O_DATA_VALID && !I_DATA_READY) begin
        r_stalled = r_stalled + 1;
        if (O_DATA_LAST)
          r_last_stalled = r_last_stalled + 1;
      end

      // Check selected primitive LAST timing independently of the wrapper.
      if (u_dut.w_child_output_valid && u_dut.w_child_output_ready) begin
        if (u_dut.w_child_output_last !==
            (r_child_beat == ((4 << (r_completed/8))/4)-1))
          $fatal(1, "[FAIL] Child LAST TC=%0d childbeat=%0d", r_completed, r_child_beat);
        r_child_beat = r_child_beat + 1;
      end

      if (O_DATA_VALID && I_DATA_READY) begin
        if (r_completed >= PARA_TC_COUNT)
          $fatal(1, "[FAIL] Unexpected extra vector");
        r_expected_size = 4 << (r_completed / 8);
        if (O_DATA_LAST !== (r_output_beat == r_expected_size/4 - 1))
          $fatal(1, "[FAIL] LAST TC=%0d beat=%0d", r_completed, r_output_beat);
        for (integer lane = 0; lane < 4; lane++) begin
          r_sample_idx = 4*r_output_beat + lane;
          w_sample = $signed(O_DATA[lane*PARA_RESULT_WD +: PARA_RESULT_WD]);
          r_rtl_result[r_sample_idx] = w_sample;
          if (w_sample !== r_golden[r_completed][r_sample_idx])
            $fatal(1, "[FAIL] TC%0d N=%0d mode=%0d X[%0d] RTL=%0d GOLDEN=%0d",
              r_completed+1, r_expected_size, (r_completed%2), r_sample_idx,
              w_sample, r_golden[r_completed][r_sample_idx]);
        end
        if (O_DATA_LAST) begin
          if (r_child_beat != r_expected_size/4)
            $fatal(1, "[FAIL] Missing child beats: TC%0d got %0d", r_completed, r_child_beat);
          $display("=============================================================");
          $display("[PASS TC%0d] %s, N=%0d",r_completed+1,(r_completed%2)?"IDCT8":"IDST7",r_expected_size);
          $display("  Input coefficients:");
          for (integer p = 0; p < r_expected_size; p += 4)
            $display("    C[%0d..%0d]=%0d %0d %0d %0d",p,p+3,
              r_coefficients[r_completed][p],r_coefficients[r_completed][p+1],
              r_coefficients[r_completed][p+2],r_coefficients[r_completed][p+3]);
          $display("  Raw reconstructed spatial samples RTL = GOLDEN:");
          for (integer p = 0; p < r_expected_size; p += 4)
            $display("    X[%0d..%0d]=%0d %0d %0d %0d",p,p+3,
              r_rtl_result[p],r_rtl_result[p+1],r_rtl_result[p+2],r_rtl_result[p+3]);
          r_completed = r_completed + 1;
          r_output_beat = 0;
          r_child_beat = 0;
        end
        else
          r_output_beat = r_output_beat + 1;
      end
      r_previous_stall = O_DATA_VALID && !I_DATA_READY;
      r_previous_data = O_DATA;
      r_previous_last = O_DATA_LAST;
    end
  end

  task automatic send_vector(input integer tc);
    integer n;
    integer nbeats;
    logic [1:0] size_code;
    logic mode;
    begin
      size_code = 2'(tc/8);
      mode = 1'(tc%2);
      n = 4 << size_code;
      nbeats = n/4;
      for (integer beat = 0; beat < nbeats; beat++) begin
        @(posedge I_CLK);
        I_DATA_VALID <= 1'b1;
        I_TRANSFORM_SIZE <= size_code;
        I_TRANSFORM_MODE <= mode;
        for (integer lane = 0; lane < 4; lane++)
          I_DATA[lane*PARA_DATA_WD +: PARA_DATA_WD] <= 16'(r_coefficients[tc][beat*4+lane]);
        do @(posedge I_CLK); while (!O_DATA_READY);
        I_DATA_VALID <= 1'b0;
        // Include occasional gaps within one transform vector.
        if ((beat % 2) == 0)
          @(posedge I_CLK);
      end
    end
  endtask

